#!/usr/bin/env python3
"""Relocate staged bottles to Darwin paths, preserving Mach-O code/signatures.

Homebrew placeholders are installation metadata, not dyld path syntax. Use
LLVM's Mach-O writer for install names/rpaths and ad-hoc signing; only bounded
__cstring entries are patched in place. Unsupported binary layouts fail before
publication. Original bottle archives remain unchanged.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import struct
import subprocess
import tempfile

TOKENS = (b"@@HOMEBREW_PREFIX@@", b"@@HOMEBREW_CELLAR@@", b"@@HOMEBREW_REPOSITORY@@")
DYLIB_COMMANDS = {0xC, 0x80000018, 0x8000001F, 0x80000023, 0x20}


def contains_tokens(data):
    return any(token in data for token in TOKENS)


def replace(data, mappings):
    for token, value in mappings.items():
        data = data.replace(token, value)
    return data


def macho_layout(data):
    if len(data) < 32 or struct.unpack_from("<I", data)[0] != 0xFEEDFACF:
        raise ValueError("relocation currently requires a thin little-endian 64-bit Mach-O")
    commands, strings = [], []
    ncmds, sizeofcmds = struct.unpack_from("<II", data, 16)
    end, offset = 32 + sizeofcmds, 32
    if end > len(data):
        raise ValueError("truncated Mach-O commands")
    for _ in range(ncmds):
        if offset + 8 > end:
            raise ValueError("truncated Mach-O command")
        command, size = struct.unpack_from("<II", data, offset)
        if size < 8 or offset + size > end:
            raise ValueError("invalid Mach-O command size")
        if command in DYLIB_COMMANDS | {0xD, 0x8000001C}:
            if size < 12:
                raise ValueError("truncated path command")
            relative = struct.unpack_from("<I", data, offset + 8)[0]
            if relative < 12 or relative >= size:
                raise ValueError("invalid Mach-O path offset")
            path = data[offset + relative:offset + size].split(b"\0", 1)[0]
            commands.append((command, path))
        if command == 0x19:
            if size < 72:
                raise ValueError("truncated segment")
            nsections = struct.unpack_from("<I", data, offset + 64)[0]
            if 72 + 80 * nsections > size:
                raise ValueError("truncated sections")
            for i in range(nsections):
                section = offset + 72 + i * 80
                length = struct.unpack_from("<Q", data, section + 40)[0]
                file_offset = struct.unpack_from("<I", data, section + 48)[0]
                flags = struct.unpack_from("<I", data, section + 64)[0]
                if flags & 255 == 2:  # S_CSTRING_LITERALS
                    if file_offset + length > len(data):
                        raise ValueError("truncated cstring section")
                    strings.append((file_offset, file_offset + length))
        offset += size
    if offset != end:
        raise ValueError("inconsistent Mach-O command count")
    return commands, strings


def patch_cstrings(data, sections, mappings):
    output = bytearray(data)
    for begin, end in sections:
        at = begin
        while at < end:
            stop = data.find(b"\0", at, end)
            if stop < 0:
                raise ValueError("unterminated Mach-O cstring")
            old = data[at:stop]
            new = replace(old, mappings)
            if len(new) > len(old):
                raise ValueError("target prefix is too long for an embedded Mach-O path")
            output[at:stop] = new + b"\0" * (len(old) - len(new))
            at = stop + 1
    return bytes(output)


def verify_code_signature(data):
    """Verify executable page hashes regenerated by LLVM's Mach-O writer."""
    offset = 32
    for _ in range(struct.unpack_from("<I", data, 16)[0]):
        command, size = struct.unpack_from("<II", data, offset)
        if command == 0x1D:
            start, length = struct.unpack_from("<II", data, offset + 8)
            if start + length > len(data):
                raise ValueError("truncated code signature")
            magic, total, count = struct.unpack_from(">III", data, start)
            if magic != 0xFADE0CC0 or total > length or 12 + count * 8 > total:
                raise ValueError("invalid signature superblob")
            checked = False
            for i in range(count):
                kind, relative = struct.unpack_from(">II", data, start + 12 + i * 8)
                if kind != 0 and not 0x1000 <= kind < 0x1005:
                    continue
                directory = start + relative
                fields = struct.unpack_from(">9I4B", data, directory)
                cdmagic, cdlength, _, flags, hash_offset, _, _, slots, limit, width, algorithm, _, page = fields
                if cdmagic != 0xFADE0C02 or relative + cdlength > total or page > 30:
                    raise ValueError("invalid CodeDirectory")
                if hash_offset + slots * width > cdlength or limit > start:
                    raise ValueError("invalid code hash bounds")
                digest = {1: hashlib.sha1, 2: hashlib.sha256, 3: hashlib.sha256}.get(algorithm)
                if not digest or not flags & 2:
                    raise ValueError("expected a supported ad-hoc CodeDirectory after relocation")
                page_size = 1 << page
                if slots != (limit + page_size - 1) // page_size:
                    raise ValueError("invalid code page count")
                for slot in range(slots):
                    expected = digest(data[slot * page_size:min((slot + 1) * page_size, limit)]).digest()[:width]
                    position = directory + hash_offset + slot * width
                    if data[position:position + width] != expected:
                        raise ValueError("invalid relocated code signature page hash")
                checked = True
            if not checked:
                raise ValueError("code signature has no CodeDirectory")
            return True
        offset += size
    return False


def save_report(path, report):
    temporary = path.with_suffix(".json.partial")
    temporary.write_text(json.dumps(report, indent=2) + "\n")
    temporary.replace(path)


def relocate(venv, prefix, tool, check_only=False):
    cellar = venv / prefix.lstrip("/") / "Cellar"
    if not cellar.is_dir():
        raise ValueError("no staged Cellar at " + str(cellar))
    if not cellar.resolve().is_relative_to(venv):
        raise ValueError("Cellar points outside the venv")
    mappings = dict(zip(TOKENS, (prefix.encode(), (prefix + "/Cellar").encode(), prefix.encode())))
    changed = []
    for path in sorted(cellar.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        data = path.read_bytes()
        if contains_tokens(data):
            changed.append((path, data))
    report_path = venv / ".machoman/bootstrap/homebrew-relocation.json"
    if not report_path.parent.resolve().is_relative_to(venv):
        raise ValueError("bootstrap directory points outside the venv")
    if check_only:
        invalid = []
        if report_path.exists():
            report = json.loads(report_path.read_text())
            for relative, record in report["files"].items():
                path = venv / relative
                if not path.resolve().is_relative_to(venv) or not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != record["relocated_sha256"]:
                    invalid.append(relative)
            if report["state"] != "complete" or report["prefix"] != prefix:
                invalid.append("relocation journal")
        print(f"{len(changed)} files contain placeholders; {len(invalid)} relocated files/journals failed verification")
        return 1 if changed or invalid else 0
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report = json.loads(report_path.read_text()) if report_path.exists() else {
        "schema_version": 1, "prefix": prefix, "files": {}}
    if report["prefix"] != prefix:
        raise ValueError("changing the prefix requires restaging the original bottles")
    with tempfile.TemporaryDirectory(prefix="relocation-", dir=report_path.parent) as temporary:
        plans = []
        for path, original in changed:
            relative = path.relative_to(venv)
            staged = Path(temporary) / relative
            staged.parent.mkdir(parents=True, exist_ok=True)
            signed = False
            if original[:4] == b"\xcf\xfa\xed\xfe":
                commands, sections = macho_layout(original)
                staged.write_bytes(patch_cstrings(original, sections, mappings))
                arguments = []
                for command, old in commands:
                    new = replace(old, mappings)
                    if old == new:
                        continue
                    if command == 0xD:
                        arguments += ["-id", new.decode()]
                    elif command == 0x8000001C:
                        arguments += ["-rpath", old.decode(), new.decode()]
                    else:
                        arguments += ["-change", old.decode(), new.decode()]
                output = staged.with_name(staged.name + ".signed")
                subprocess.run([tool, *arguments, "--output", str(output), str(staged)],
                               check=True, capture_output=True, text=True)
                output.replace(staged)
                data = staged.read_bytes()
                macho_layout(data)
                signed = verify_code_signature(data)
            else:
                if b"\0" in original:
                    raise ValueError("unsupported binary placeholder in " + str(relative))
                original.decode("utf-8")
                data = replace(original, mappings)
                staged.write_bytes(data)
            if contains_tokens(data):
                raise ValueError("unhandled binary placeholder in " + str(relative))
            shutil.copystat(path, staged)
            report["files"][relative.as_posix()] = {
                "original_sha256": hashlib.sha256(original).hexdigest(),
                "relocated_sha256": hashlib.sha256(data).hexdigest(),
                "adhoc_signature_verified": signed,
            }
            plans.append((path, staged))
        # All files have been prepared and validated before the first publish.
        # A journal distinguishes an interrupted commit from a completed one.
        report["state"] = "committing"
        save_report(report_path, report)
        for path, staged in plans:
            os.replace(staged, path)
        report["state"] = "complete"
        save_report(report_path, report)
    print(f"Relocated {len(changed)} files to {prefix}; original archives preserved")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--venv", required=True, type=Path)
    parser.add_argument("--prefix", default="/opt/homebrew")
    parser.add_argument("--install-name-tool", default="llvm-install-name-tool")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = PurePosixPath(args.prefix)
    if not path.is_absolute() or ".." in path.parts or str(path) == "/" or "\0" in args.prefix:
        parser.error("prefix must be an absolute guest directory without '..' or NUL")
    try:
        return relocate(args.venv.resolve(), str(path), args.install_name_tool, args.check)
    except (ValueError, OSError, struct.error, subprocess.CalledProcessError) as error:
        parser.exit(1, f"relocation failed: {error}\n")


if __name__ == "__main__":
    raise SystemExit(main())
